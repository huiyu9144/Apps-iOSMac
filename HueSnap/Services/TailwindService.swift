import Foundation

struct TailwindColor {
    let name: String
    let hex: String
    let red: Int
    let green: Int
    let blue: Int
}

class TailwindService {
    private var colors: [TailwindColor] = []

    init() {
        loadColors()
    }

    private func loadColors() {
        colors = Self.tailwindColors
    }

    func closestMatch(red: Double, green: Double, blue: Double) -> (name: String, hex: String) {
        let r = Int(red * 255)
        let g = Int(green * 255)
        let b = Int(blue * 255)

        var bestMatch = colors.first!
        var bestDistance = Double.infinity

        for color in colors {
            let dr = Double(color.red - r)
            let dg = Double(color.green - g)
            let db = Double(color.blue - b)
            let distance = dr * dr + dg * dg + db * db

            if distance < bestDistance {
                bestDistance = distance
                bestMatch = color
            }
        }

        return (bestMatch.name, bestMatch.hex)
    }

